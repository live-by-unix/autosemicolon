export function getLanguageCapability(languageId: string): LanguageCapability | undefined {
  return LANGUAGE_CAPABILITIES.get(languageId);
}

export function isLanguageSupported(languageId: string): boolean {
  const capability = LANGUAGE_CAPABILITIES.get(languageId);
  return capability !== undefined && capability.supportLevel !== 'disabled';
}

export function isLanguageEnabledByDefault(languageId: string): boolean {
  const capability = LANGUAGE_CAPABILITIES.get(languageId);
  return capability !== undefined && capability.enabledByDefault;
}
